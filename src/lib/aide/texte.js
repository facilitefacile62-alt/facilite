// Normalisation de texte partagée (côté navigateur et serveur : aucune dépendance Node ici).
export function normaliserQuestion(texte) {
  return String(texte || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}
